import { createHash, randomUUID } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { test, local2691 } from "../helpers/2691-admin";
import { newProject, newTask } from "../helpers/migration-2731";
import { clickAboveTabBar } from "../helpers/screen-row";
import { expect, zz } from "./qa";

test("SHO-REG-TASKS-13 phone delete and Undo restores a parent and child without touching another project", async ({ admin, later }) => {
  if (!local2691) throw new Error("Task deletion browser audit requires the guarded local test database.");
  const fixture = randomUUID();
  const evidenceDir = "test-results/task-delete-undo-browser";
  let projectId = "";
  let sentinelId = "";
  later(async () => {
    if (!projectId || !sentinelId) return;
    const source = await admin.api.get(`/api/projects/${projectId}`);
    const sentinelProject = await admin.api.get(`/api/projects/${sentinelId}`);
    expect(source.status).toBe(200);
    expect(sentinelProject.status).toBe(200);
    expect(source.json.project.archived).toBe(true);
    expect(sentinelProject.json.project.archived).toBe(true);
    mkdirSync(evidenceDir, { recursive: true });
    writeFileSync(`${evidenceDir}/cleanup.json`, JSON.stringify({ fixture, projectId, sentinelId, projectsArchived: true, cleanup: true }, null, 2));
  });
  const sentinel = await newProject(admin, later, { label: "task delete Undo sentinel" });
  sentinelId = sentinel.id;
  const project = await newProject(admin, later, { label: "task delete Undo source" });
  projectId = project.id;
  const title = zz("task delete Undo parent");
  const parentId = await newTask(admin, project.id, { title });
  const childId = await newTask(admin, project.id, { title: zz("task delete Undo child"), parentId });
  const parentBefore = (await admin.api.get(`/api/tasks/${parentId}`)).json.task;
  const childBefore = (await admin.api.get(`/api/tasks/${childId}`)).json.task;
  const sentinelBefore = (await admin.api.get(`/api/projects/${sentinel.id}`)).json.project;
  const sentinelHash = createHash("sha256").update(JSON.stringify(sentinelBefore)).digest("hex");
  const page = admin.page;
  await page.setViewportSize({ width: 390, height: 800 });
  await page.goto(`/projects/${project.id}?task=${parentId}`);
  const task = page.getByRole("dialog", { name: "Task", exact: true });
  await expect(task).toBeVisible();
  await clickAboveTabBar(task.getByRole("button", { name: "Move to Trash", exact: true }));
  const confirm = page.getByRole("dialog", { name: "Move to Trash?" });
  await expect(confirm).toBeVisible();
  await confirm.getByRole("button", { name: "Move to Trash" }).click();
  const toast = page.getByRole("status").filter({ hasText: "Task deleted" });
  await expect(toast.getByRole("button", { name: "Undo" })).toBeVisible();
  expect((await admin.api.get(`/api/tasks/${parentId}`)).status).toBe(404);
  expect((await admin.api.get(`/api/tasks/${childId}`)).status).toBe(404);
  const activity = await admin.api.get(`/api/projects/${project.id}/activity`);
  expect(activity.status).toBe(200);
  const deleted = (activity.json.items as { id: string; what: string }[]).find(item => item.what.includes(title) && item.what.includes("Trash"));
  expect(deleted).toBeDefined();
  mkdirSync(evidenceDir, { recursive: true });
  await page.screenshot({ path: `${evidenceDir}/deleted.png`, fullPage: true });

  await toast.getByRole("button", { name: "Undo" }).click();
  await expect.poll(async () => (await admin.api.get(`/api/tasks/${parentId}`)).status).toBe(200);
  await expect.poll(async () => (await admin.api.get(`/api/tasks/${childId}`)).status).toBe(200);
  const parentAfter = (await admin.api.get(`/api/tasks/${parentId}`)).json.task;
  const childAfter = (await admin.api.get(`/api/tasks/${childId}`)).json.task;
  expect(parentAfter.sectionId).toBe(parentBefore.sectionId);
  expect(childAfter.parentId).toBe(parentId);
  expect(childAfter.sectionId).toBe(childBefore.sectionId);
  expect((await admin.api.post(`/api/actions/${deleted!.id}/undo`, {})).status).toBe(409);
  const trash = await admin.api.get(`/api/projects/${project.id}/trash`);
  expect(trash.status).toBe(200);
  expect((trash.json.items as { id: string }[]).map(item => item.id)).not.toContain(parentId);
  expect((trash.json.items as { id: string }[]).map(item => item.id)).not.toContain(childId);
  const sentinelAfter = (await admin.api.get(`/api/projects/${sentinel.id}`)).json.project;
  expect(createHash("sha256").update(JSON.stringify(sentinelAfter)).digest("hex")).toBe(sentinelHash);
  writeFileSync(`${evidenceDir}/verification.json`, JSON.stringify({ fixture, projectId: project.id, parentId, childId, deleteActionId: deleted!.id, mobileWidth: 390, parentAndChildHidden: true, toastUndoUsed: true, sectionAndParentPreserved: true, replayRejected: true, trashClear: true, sentinelPreserved: true }, null, 2));
});
