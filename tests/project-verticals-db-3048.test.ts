import { afterAll, expect, it } from "vitest";
import { db } from "@/lib/db";
import { account, cleanupZz, project, superAdmin, task, type Account } from "./helpers";
const projects: string[] = [];
const people: Account[] = [];
afterAll(async () => cleanupZz(projects, people));
it("SHO-3048 preserves legacy board identity/work and does not inherit vertical access", async () => {
  const sa = await superAdmin();
  const verticalMember = await account("ZZ-TEST vertical-only member"); people.push(verticalMember);
  const p = await project(sa, sa, [], `ZZ-TEST legacy vertical ${Date.now()}`); projects.push(p.id);
  const taskId = await task(sa, p.id);
  const beforeTask = await db.task.findUniqueOrThrow({ where: { id: taskId } });
  const beforeMembers = await db.projectMember.findMany({ where: { projectId: p.id }, orderBy: { userId: "asc" } });
  expect((await sa.c.get(`/api/projects/${p.id}`)).json.project.isVertical).toBe(false);
  expect((await verticalMember.c.post(`/api/projects/${p.id}/classification`, { isVertical: true })).status).toBe(403);
  expect((await sa.c.post(`/api/projects/${p.id}/classification`, { isVertical: true })).status).toBe(200);
  expect(await db.task.findUniqueOrThrow({ where: { id: taskId } })).toEqual(beforeTask);
  expect(await db.projectMember.findMany({ where: { projectId: p.id }, orderBy: { userId: "asc" } })).toEqual(beforeMembers);
  expect((await sa.c.get(`/api/tasks/${taskId}`)).status).toBe(200);
  expect((await sa.c.post(`/api/projects/${p.id}/members`, { userId: verticalMember.id, role: "EDITOR" })).status).toBe(201);
  const delivery = await sa.c.post("/api/projects", { name: `ZZ-TEST delivery ${Date.now()}`, leaderId: sa.id, verticalId: p.id });
  expect(delivery.status).toBe(201); const deliveryId = delivery.json.project.id; projects.push(deliveryId);
  const visible = (await sa.c.get(`/api/projects/${deliveryId}`)).json.project;
  expect(visible).toMatchObject({ isVertical: false, verticalId: p.id });
  expect((await verticalMember.c.get(`/api/projects/${p.id}`)).status).toBe(200);
  expect((await verticalMember.c.get(`/api/projects/${deliveryId}`)).status).toBe(404);
  expect((await verticalMember.c.patch(`/api/projects/${p.id}`, { name: "Unauthorized rename" })).status).toBe(403);
  expect((await sa.c.post(`/api/projects/${p.id}/classification`, { isVertical: false })).status).toBe(409);
  expect((await sa.c.post(`/api/projects/${p.id}/archive`)).status).toBe(200);
  const invalid = await sa.c.post("/api/projects", { name: "ZZ-TEST retired vertical refusal", leaderId: sa.id, verticalId: p.id });
  expect(invalid.status).toBe(400);
  expect((await sa.c.get(`/api/projects/${deliveryId}`)).json.project.verticalId).toBe(p.id);
  expect((await sa.c.patch(`/api/projects/${deliveryId}`, { verticalId: null })).status).toBe(200);
  expect((await sa.c.get(`/api/projects/${deliveryId}`)).json.project.verticalId).toBeNull();
});
