import { newTurn, runTool } from "../src/lib/concierge/tools";
import { randomUUID } from "node:crypto";
import { expect, it } from "vitest";
import { account, admin, superAdmin, istDate } from "./helpers";
it("SHO-2588 warns across the tree and buyers, checks contacts, and permanently dismisses review pairs", async () => {
  const member = await account("duplicates2588");
  const reviewer = await admin(await superAdmin(), "duplicateAdmin2588");
  const tag = randomUUID();
  const make = async (name: string, parentId?: string) => {
    const r = await member.c.post("/api/orgs", { name, parentId, force: true });
    expect(r.status).toBe(201); return r.json.organisation.id as string;
  };
  const first = await make(`Ministry of Education ${tag}`);
  const parent = await make(randomUUID());
  const warning = await member.c.post("/api/orgs", { name: `Ministry for Education ${tag}`, parentId: parent });
  expect(warning.status).toBe(409); expect(warning.json.existingId).toBe(first);
  const turn = newTurn({ id: member.id, orgRole: "MEMBER" }, new Date());
  const lookup = await runTool(turn, "find_account_records", { text: `Ministry of Education ${tag}` });
  expect(lookup.isError).not.toBe(true);
  expect(JSON.parse(lookup.content).untrusted_data).toMatchObject({ creationSupported: false, records: expect.arrayContaining([expect.objectContaining({ id: first })]) });
  const forbidden = await runTool(turn, "propose_changes", { changes: [{ action: "create_organisation", name: "Must not create" }] });
  expect(forbidden.isError).toBe(true);
  const second = await make(`Ministry for Education ${tag}`, parent);
  const email = `${tag}@example.com`;
  const c = await member.c.post(`/api/orgs/${first}/contacts`, { name: "Alexandra Smith", email });
  expect(c.status).toBe(201);
  expect((await member.c.post(`/api/orgs/${second}/contacts`, { name: "Unrelated Person", email: email.toUpperCase() })).status).toBe(409);
  expect((await member.c.post(`/api/orgs/${first}/contacts`, { name: "Alexandra Smyth" })).status).toBe(409);
  const other = await member.c.post(`/api/orgs/${first}/contacts`, { name: "Alexandra Smyth", force: true });
  expect(other.status).toBe(201);
  const pipes = await member.c.get("/api/deals/pipelines");
  const body = { name: `Education transformation ${tag}`, organisationId: first, pipelineId: pipes.json.pipelines[0].id, leaderId: member.id, whyPursue: "Strong fit", nextStep: { title: "Call", dueDate: istDate(2) }, force: true };
  const madeDeal = await member.c.post("/api/deals", body);
  expect(madeDeal.status).toBe(201);
  const dealWarning = await member.c.post("/api/deals", { ...body, name: `Education transformations ${tag}`, organisationId: second, force: false });
  expect(dealWarning.status).toBe(409);
  expect(dealWarning.json.existingId).toBe(madeDeal.json.deal.id);
  const outsider = await account("duplicateOutsider2588");
  const hiddenWarning = await outsider.c.post("/api/deals", { ...body, organisationId: second, leaderId: outsider.id, force: false });
  expect(hiddenWarning.status).toBe(409);
  expect(hiddenWarning.json.needsConfirm).toBe("duplicate");
  expect(JSON.stringify(hiddenWarning.json)).not.toContain(madeDeal.json.deal.id);
  expect(JSON.stringify(hiddenWarning.json)).not.toContain(body.name);
  expect(hiddenWarning.json.existingId).toBeUndefined();
  expect((await member.c.get("/api/accounts/duplicates")).status).toBe(403);
  const pairs = await reviewer.c.get("/api/accounts/duplicates");
  expect(pairs.status).toBe(200);
  const pair = pairs.json.pairs.find((p: { leftId: string; rightId: string }) => [p.leftId, p.rightId].includes(c.json.contact.id) && [p.leftId, p.rightId].includes(other.json.contact.id));
  expect(pair).toBeTruthy();
  expect((await reviewer.c.post("/api/accounts/duplicates", pair)).status).toBe(200);
  expect((await reviewer.c.post("/api/accounts/duplicates", pair)).status).toBe(200);
  const again = await reviewer.c.get("/api/accounts/duplicates");
  expect(again.json.pairs.some((p: { leftId: string; rightId: string }) => p.leftId === pair.leftId && p.rightId === pair.rightId)).toBe(false);
  expect((await member.c.get(`/api/orgs/${first}`)).status).toBe(200);
});
